// Concatenate every migration into supabase/setup-all.sql, so a new Supabase
// project can be set up by pasting one file into the SQL editor.
// Run: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const parts = files.map((f) => `-- ===== ${f} =====\n${readFileSync(`${dir}/${f}`, "utf8").trim()}\n`);
writeFileSync(
  "supabase/setup-all.sql",
  `-- Generated by scripts/db/bundle.mjs from supabase/migrations — do not edit by hand.\n-- Paste into Supabase → SQL Editor → New query → Run, on a NEW, empty project (once).\n\n${parts.join("\n")}`,
);
console.log(`supabase/setup-all.sql: ${files.length} migrations`);
